import { z } from "zod";
import { contentTypes } from "./linkCategorizer.js";

// User validation schemas
export const signupSchema = z.object({
  username: z.string().min(3, "Username must be at least 3 characters").max(50),
  password: z
    .string()
    .min(6, "Password must be at least 6 characters")
    .max(100),
});

export const signinSchema = z.object({
  username: z.string().min(3).max(50),
  password: z.string().min(6).max(100),
});

// Content validation schemas
export const createContentSchema = z.object({
  link: z
    .string()
    .url("Invalid URL format")
    .refine(
      (value) => /^https?:\/\//i.test(value),
      "Use an HTTP or HTTPS link",
    ),
  title: z.string().min(1).max(200).optional(), // Optional, will be auto-generated by AI
  type: z.enum(contentTypes as any).optional(), // Optional, will be auto-detected
  description: z.string().max(1000).optional(),
  thumbnail: z.string().url().optional(),
  sourceText: z
    .string()
    .trim()
    .min(20, "Add at least 20 characters of post text")
    .max(80000)
    .optional(),
});

export const updateContentSchema = z.object({
  link: z.string().url().optional(),
  title: z.string().min(1).max(200).optional(),
  type: z.enum(contentTypes as any).optional(),
  description: z.string().max(1000).optional(),
  thumbnail: z.string().url().optional(),
});

export const sourceTextSchema = z.object({
  sourceText: z
    .string()
    .trim()
    .min(20, "Add at least 20 characters of post text")
    .max(80000),
  title: z.string().trim().min(1).max(200).optional(),
});

export const contentIdSchema = z.object({
  contentId: z.string().min(1, "Content ID is required"),
});

// Link sharing validation
export const shareLinkSchema = z.object({
  share: z.boolean(),
});

// Query parameter validation
export const contentFilterSchema = z.object({
  type: z.enum(contentTypes as any).optional(),
  category: z
    .enum([
      "social",
      "video",
      "code",
      "article",
      "audio",
      "image",
      "document",
      "other",
    ] as const)
    .optional(),
  limit: z.string().regex(/^\d+$/).transform(Number).optional(),
  offset: z.string().regex(/^\d+$/).transform(Number).optional(),
});

export const searchQuerySchema = z.object({
  q: z
    .string()
    .max(500)
    .transform((value) => value.normalize("NFKC").trim().replace(/\s+/g, " "))
    .pipe(z.string().min(1, "Search query is required")),
  limit: z.coerce.number().int().min(1).max(50).default(10),
});

// Type exports for use in the application
export type SignupInput = z.infer<typeof signupSchema>;
export type SigninInput = z.infer<typeof signinSchema>;
export type CreateContentInput = z.infer<typeof createContentSchema>;
export type UpdateContentInput = z.infer<typeof updateContentSchema>;
export type ContentFilterInput = z.infer<typeof contentFilterSchema>;
